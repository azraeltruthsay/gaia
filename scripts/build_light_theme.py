#!/usr/bin/env python3
"""Generate gaia-web's light theme from its dark stylesheet.

style.css has about 260 hard-coded colors besides its tokens, tuned for a dark
page: pale blues and greens that vanish on white. Overriding them by hand would
drift with every new rule, so this reads each rule and writes its light
counterpart. Run it after changing style.css:

    python3 scripts/build_light_theme.py candidates/gaia-web/static
"""
import re
import sys
from pathlib import Path

TOKENS = """\
  --bg-primary: #f5f6f8; --bg-panel: #ffffff; --bg-card: #eceff4; --accent: #dde3ec;
  --highlight: #c2213f; --text: #1f2733; --text-muted: #4f5a69; --text-bright: #0e131a;
  --text-dim: #5b6675; --border: #c5cdd9; --border-dim: rgba(0, 0, 0, 0.1);
  --success: #1b7a2f; --warn: #8f5400; --error: #b3203a;
  --bg-active: rgba(194, 33, 63, 0.1); --bg-hover: rgba(0, 0, 0, 0.04);
  --accent-cyan: #00687a; --accent-cyan-bright: #004d5c; --accent-cyan-dim: rgba(0, 104, 122, 0.12);
  --glow-nominal: none; --glow-attention: none; --glow-alarm: none; --hud-scanline: none;
  --green: #1b7a2f; --red: #b3203a; --yellow: #8f5400; --ok: #1b7a2f;
  --panel-bg: #ffffff; --bg: #f5f6f8;
  /* Easier to read: the portal's text was monospace. Code stays monospace below. */
  --font-code: 'JetBrains Mono', 'Fira Code', 'Cascadia Code', monospace;
  --font-mono: 'Inter', 'Segoe UI', system-ui, -apple-system, sans-serif;
"""

TEXT = {
    "#4fc3f7": "#01579b", "#42a5f5": "#0d47a1", "#90caf9": "#0d47a1", "#29b6f6": "#01579b", "#81d4fa": "#01579b",
    "#4caf50": "#1b6e20", "#66bb6a": "#1b6e20", "#22c55e": "#1b6e20", "#81c784": "#1b6e20", "#a5d6a7": "#1b6e20",
    "#ffa726": "#8a4b00", "#ffb74d": "#8a4b00", "#ff9800": "#8a4b00", "#fff176": "#7a5a00", "#ffd54f": "#7a5a00",
    "#ffcc80": "#8a4b00", "#ffeb3b": "#7a5a00", "#ffc107": "#7a5a00",
    "#ef5350": "#b3203a", "#e94560": "#b3203a", "#ff5252": "#b3203a", "#f44336": "#b3203a", "#ef9a9a": "#b3203a",
    "#ce93d8": "#6a1b9a", "#ab47bc": "#6a1b9a", "#ba68c8": "#6a1b9a", "#b39ddb": "#4527a0",
    "#fff": "#1a1f2b", "#ffffff": "#1a1f2b", "#e0e0e0": "#1f2733", "#cdd6f4": "#1f2733", "#eee": "#1f2733",
    "#ccc": "#2f3845", "#bbb": "#3d4757", "#aaa": "#4f5a69", "#a6adc8": "#4f5a69", "#8899aa": "#4f5a69",
    "#9e9e9e": "#4f5a69", "#78909c": "#4f5a69", "#757575": "#4f5a69", "#616161": "#4f5a69", "#546e7a": "#4f5a69",
    "#888": "#4f5a69", "#999": "#4f5a69", "#777": "#4f5a69", "#666": "#4f5a69", "#555": "#4f5a69",
}
BACKGROUND = {
    "#1a1a2e": "#f5f6f8", "#16213e": "#ffffff", "#0f3460": "#eceff4", "#1e1e2e": "#ffffff", "#313244": "#e4e8ee",
    "#253658": "#c5cdd9", "#111": "#ffffff", "#222": "#eceff4", "#333": "#dde3ec", "#2a2a3e": "#e4e8ee",
    "#0d1117": "#f5f6f8", "#161b22": "#ffffff", "#21262d": "#eceff4", "#30363d": "#c5cdd9",
}
# Text kept on purpose: it sits on a saturated fill of its own (buttons, solid badges).
FILLED = re.compile(r"background(-color)?\s*:\s*(var\(--(highlight|error|red|success|green|warn|yellow|ok)\)|#(e94560|ef5350|4caf50|66bb6a|ffa726|ff9800|42a5f5|ab47bc|f44336))", re.I)
# Terminals and the like stay dark in both themes. So does the brain: its glow
# and the inverted anatomy drawing wash out on white (Azrael, 2026-11-05).
KEEP_DARK = re.compile(r"xterm|terminal|\.term\b|scrim|overlay|backdrop|tooltip|neuron|unified-brain|brain-image", re.I)
BRAIN_PANEL = ('html[data-theme="light"] .unified-brain { background: #1a1a2e; border-radius: 8px; '
               'margin: 6px; box-shadow: inset 0 0 12px rgba(0, 0, 0, 0.5); }')
CODE = "pre, code, kbd, samp, textarea.code, .xterm, .xterm *, .palace-card pre"
HEX = re.compile(r"#[0-9a-fA-F]{3,8}\b")
WHITE_TINT = re.compile(r"rgba\(\s*255\s*,\s*255\s*,\s*255\s*,\s*([0-9.]+)\s*\)")
RULE = re.compile(r"([^{}]+)\{([^{}]*)\}")


def map_value(prop: str, value: str, filled: bool):
    new = value
    if prop in ("color", "fill", "stroke") and not filled:
        new = HEX.sub(lambda m: TEXT.get(m.group().lower(), m.group()), new)
    elif prop.startswith(("background", "border", "outline", "box-shadow")):
        new = HEX.sub(lambda m: BACKGROUND.get(m.group().lower(), m.group()), new)
        new = WHITE_TINT.sub(lambda m: f"rgba(0, 0, 0, {m.group(1)})", new)
    if prop == "text-shadow" and value != "none":
        return "none"
    return new if new != value else None


def scope(selectors: str) -> str:
    parts = []
    for sel in selectors.split(","):
        sel = sel.strip()
        sel = re.sub(r"^(html|body|:root)(?=$|[\s.:#>])", r"\1", sel)
        if re.match(r"^(html|:root)\b", sel):
            parts.append(f'html[data-theme="light"]{sel[sel.find(" "):] if " " in sel else ""}')
        else:
            parts.append(f'html[data-theme="light"] {sel}')
    return ", ".join(parts)


def build(css: str) -> str:
    css = re.sub(r"/\*.*?\*/", "", css, flags=re.S)
    css = re.sub(r":root\s*\{[^{}]*\}", "", css, count=1)
    out = ["/* Generated by scripts/build_light_theme.py from style.css. Do not edit. */",
           'html[data-theme="light"] {', TOKENS + "}",
           f'html[data-theme="light"] body {{ font-size: 15px; line-height: 1.5; }}',
           f'html[data-theme="light"] :is({CODE}) {{ font-family: var(--font-code); }}',
           BRAIN_PANEL]
    for match in RULE.finditer(css):
        selectors, body = match.group(1).strip(), match.group(2)
        # Inside @media or @keyframes the regex sees the inner rule; skip keyframe steps.
        selectors = selectors.split("}")[-1].split("{")[-1].strip()
        selectors = re.sub(r"^@[^;]*;\s*", "", selectors)
        if not selectors or selectors.startswith("@") or re.fullmatch(r"(from|to|[\d.]+%)(\s*,\s*[\d.]+%)*", selectors):
            continue
        if KEEP_DARK.search(selectors):
            continue
        filled = bool(FILLED.search(body))
        decls = []
        for decl in body.split(";"):
            if ":" not in decl:
                continue
            prop, value = (x.strip() for x in decl.split(":", 1))
            new = map_value(prop.lower(), value, filled)
            if new is not None:
                decls.append(f"{prop}: {new}")
        if decls:
            out.append(f"{scope(selectors)} {{ {'; '.join(decls)}; }}")
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    static = Path(sys.argv[1])
    (static / "theme-light.css").write_text(build((static / "style.css").read_text(encoding="utf-8")), encoding="utf-8")
    print((static / "theme-light.css"))
